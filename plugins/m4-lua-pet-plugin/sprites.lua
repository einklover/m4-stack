function Sprites.runs(row)
  local segs, x, n = {}, 1, #row
  while x <= n do
    if row:sub(x, x) == '1' then
      local x0 = x
      while x <= n and row:sub(x, x) == '1' do x = x + 1 end
      segs[#segs + 1] = { x0, x - x0 }
    else
      x = x + 1
    end
  end
  return segs
end
